// Writes client/plugin-module.js: the client parts of the built-in plugins (exts/) and of the
// plugins listed in config.json ("plugins": [...], installed as yapi-plugin-<name> packages).
// Client plugins are bundled at build time, so rebuild the client after changing that list.
const fs = require('fs');
const path = require('path');
const commonLib = require('../common/plugin.js');
const systemPlugins = require('../common/config.js').exts;

function configPlugins() {
  const configPath = process.env.YAPIX_CONFIG || path.resolve(__dirname, '../../config.json');
  if (!fs.existsSync(configPath)) return [];
  return JSON.parse(fs.readFileSync(configPath, 'utf8')).plugins || [];
}

function entry(plugin, from) {
  const options = plugin.options ? JSON.stringify(plugin.options) : null;
  const request = from === 'node_modules' ? `yapi-plugin-${plugin.name}/client.js` : `exts/yapi-plugin-${plugin.name}/client.js`;
  return `  ${JSON.stringify(plugin.name)}: { module: require(${JSON.stringify(request)}), options: ${options} }`;
}

module.exports = function generatePluginModule() {
  const lines = [];
  const extra = configPlugins();
  if (Array.isArray(extra) && extra.length) {
    for (const plugin of commonLib.initPlugins(extra, 'plugin')) {
      if (plugin.client && plugin.enable) lines.push(entry(plugin, 'node_modules'));
    }
  }
  for (const plugin of commonLib.initPlugins(systemPlugins, 'ext')) {
    if (plugin.client && plugin.enable) lines.push(entry(plugin, 'exts'));
  }
  const file = path.resolve(__dirname, '../client/plugin-module.js');
  fs.writeFileSync(file, `// Generated by scripts/gen-plugin-module.js\nmodule.exports = {\n${lines.join(',\n')}\n};\n`);
};

if (require.main === module) module.exports();
